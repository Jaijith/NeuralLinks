"""
Personality Prompt Generator
Builds a unique, dynamic personality prompt for each avatar from all accumulated data.
Cached in MongoDB for 24 hours, regenerated when source data changes.
"""
from typing import Dict, Any, List, Optional
from datetime import datetime, timezone, timedelta
from motor.motor_asyncio import AsyncIOMotorDatabase
import logging
import json

logger = logging.getLogger(__name__)


class PersonalityPromptGenerator:
    """
    Generates a unique personality prompt per avatar from ALL accumulated data:
    - graph_nodes (interests, traits, values)
    - users.connections (people in their life)
    - identity_memory (facts, preferences from voice)
    - User's real posts (writing style, topics, opinions)
    - User profile (bio, job, location)
    - Episodic memory (conversation history, emotional patterns)
    - Style profile (if generated by StyleLearner)

    Results are cached in 'avatar_personality_prompts' and regenerated every 24h
    or when source data changes.
    """

    CACHE_TTL_HOURS = 24

    def __init__(self, db: AsyncIOMotorDatabase):
        self.db = db

    # ------------------------------------------------------------------
    # PUBLIC
    # ------------------------------------------------------------------

    async def get_cached_personality_prompt(self, user_id: str) -> str:
        """Return the cached prompt if fresh, otherwise regenerate."""
        cached = await self.db.avatar_personality_prompts.find_one(
            {"user_id": user_id}, {"_id": 0}
        )

        if cached:
            gen_at = cached.get("generated_at")
            if gen_at:
                if isinstance(gen_at, str):
                    gen_at = datetime.fromisoformat(gen_at)
                # Ensure timezone-aware comparison
                now = datetime.now(timezone.utc)
                if gen_at.tzinfo is None:
                    gen_at = gen_at.replace(tzinfo=timezone.utc)
                age = now - gen_at
                if age < timedelta(hours=self.CACHE_TTL_HOURS):
                    return cached.get("personality_prompt", "")

        # Regenerate
        prompt = await self.generate_personality_prompt(user_id)
        return prompt

    async def generate_personality_prompt(self, user_id: str) -> str:
        """
        Build the full personality prompt from ALL data sources.
        Store in cache and return.
        """
        try:
            import asyncio

            # Fetch everything in parallel
            (
                graph_ctx,
                user_doc,
                identity_mem,
                recent_posts,
                connections,
                style_profile,
                episodic_summary,
            ) = await asyncio.gather(
                self._get_graph_context(user_id),
                self._get_user_document(user_id),
                self._get_identity_memory(user_id),
                self._get_recent_posts(user_id, limit=30),
                self._get_all_connections(user_id),
                self._get_style_profile(user_id),
                self._get_episodic_summary(user_id),
                return_exceptions=False,
            )

            sections: List[str] = []

            # --- 1. Identity narrative from graph traversal ---
            identity_narrative = graph_ctx.pop("_identity_narrative", "")
            if identity_narrative:
                sections.append(f"**Identity (from knowledge graph):**\n{identity_narrative}")

            # --- 2. Who this person is (profile) ---
            who = self._build_who_section(user_doc)
            if who:
                sections.append(who)

            # --- 3. ALL interests (tiered by strength) ---
            interests_sec = self._build_interests_section(graph_ctx, user_doc)
            if interests_sec:
                sections.append(interests_sec)

            # --- 4. Traits & values ---
            traits_sec = self._build_traits_values_section(graph_ctx)
            if traits_sec:
                sections.append(traits_sec)

            # --- 5. ALL connections ---
            conns_sec = self._build_connections_section(connections)
            if conns_sec:
                sections.append(conns_sec)

            # --- 6. Communication style ---
            style_sec = self._build_style_section(style_profile, recent_posts)
            if style_sec:
                sections.append(style_sec)

            # --- 7. Facts & preferences from voice ---
            facts_sec = self._build_facts_section(identity_mem)
            if facts_sec:
                sections.append(facts_sec)

            # --- 8. Emotional patterns ---
            emo_sec = self._build_emotional_section(episodic_summary)
            if emo_sec:
                sections.append(emo_sec)

            personality_prompt = "\n\n".join(sections)

            # Store in cache
            await self._store_cache(user_id, personality_prompt, graph_ctx, connections, style_profile)

            return personality_prompt

        except Exception as e:
            logger.error(f"Error generating personality prompt for {user_id}: {e}")
            return ""

    async def invalidate_cache(self, user_id: str):
        """Invalidate personality prompt cache (call when source data changes)."""
        await self.db.avatar_personality_prompts.delete_one({"user_id": user_id})

    # ------------------------------------------------------------------
    # SECTION BUILDERS
    # ------------------------------------------------------------------

    def _build_who_section(self, user_doc: Dict[str, Any]) -> str:
        if not user_doc:
            return ""
        parts = []
        name = user_doc.get("name", "")
        if name:
            parts.append(f"Name: {name}")
        bio = user_doc.get("bio", "")
        if bio:
            parts.append(f"Bio: {bio}")
        job = user_doc.get("job_title", user_doc.get("avatar_job_title", ""))
        if job:
            parts.append(f"Work: {job}")
        loc = user_doc.get("location", user_doc.get("avatar_location", ""))
        if loc:
            parts.append(f"Location: {loc}")
        age = user_doc.get("age")
        if age:
            parts.append(f"Age: {age}")
        if not parts:
            return ""
        return "**Who they are:**\n" + "\n".join(f"  {p}" for p in parts)

    def _build_interests_section(self, graph_ctx: Dict[str, Any], user_doc: Dict[str, Any]) -> str:
        interests = graph_ctx.get("interests", [])
        # Also merge profile interests
        profile_interests = user_doc.get("interests", []) if user_doc else []
        # De-duplicate
        seen = {i.get("label", "").lower() for i in interests}
        for pi in profile_interests:
            if isinstance(pi, str) and pi.lower() not in seen:
                interests.append({"label": pi, "strength": 0.6})
                seen.add(pi.lower())

        if not interests:
            return ""

        core = [i for i in interests if i.get("strength", 0) >= 0.8]
        strong = [i for i in interests if 0.5 <= i.get("strength", 0) < 0.8]
        casual = [i for i in interests if i.get("strength", 0) < 0.5]

        lines = ["**Their interests:**"]
        if core:
            lines.append(f"  Core passions: {', '.join(i.get('label', '') for i in core)}")
        if strong:
            lines.append(f"  Strong interests: {', '.join(i.get('label', '') for i in strong)}")
        if casual:
            lines.append(f"  Also into: {', '.join(i.get('label', '') for i in casual[:15])}")
        return "\n".join(lines)

    def _build_traits_values_section(self, graph_ctx: Dict[str, Any]) -> str:
        traits = graph_ctx.get("traits", [])
        values = graph_ctx.get("values", [])
        if not traits and not values:
            return ""
        lines = ["**Personality traits & values:**"]
        if traits:
            lines.append(f"  Traits: {', '.join(t.get('label', '') for t in traits[:10])}")
        if values:
            lines.append(f"  Values: {', '.join(v.get('label', '') for v in values[:10])}")
        return "\n".join(lines)

    def _build_connections_section(self, connections: List[Dict[str, Any]]) -> str:
        if not connections:
            return ""

        family = [c for c in connections if self._is_family(c)]
        friends = [c for c in connections if self._is_friend(c)]
        colleagues = [c for c in connections if self._is_colleague(c)]
        others = [c for c in connections if c not in family + friends + colleagues]

        lines = ["**People in their life:**"]
        if family:
            lines.append("  Family: " + ", ".join(
                f"{c.get('name', '')} ({c.get('relationship', '')})"
                for c in family
            ))
        if friends:
            lines.append("  Friends: " + ", ".join(
                f"{c.get('name', '')}" + (f" — {c.get('details', '')}" if c.get('details') else "")
                for c in friends
            ))
        if colleagues:
            lines.append("  Work: " + ", ".join(
                f"{c.get('name', '')} ({c.get('relationship', '')})"
                for c in colleagues
            ))
        if others:
            lines.append("  Others: " + ", ".join(
                f"{c.get('name', '')} ({c.get('relationship', '')})"
                for c in others
            ))
        return "\n".join(lines)

    def _build_style_section(self, style_profile: Optional[Dict[str, Any]], posts: List[Dict[str, Any]]) -> str:
        lines = ["**How they communicate:**"]
        has_content = False

        if style_profile:
            avg_len = style_profile.get("avg_post_length")
            if avg_len:
                lines.append(f"  Average post length: ~{int(avg_len)} words")
                has_content = True
            tone = style_profile.get("tone_distribution", {})
            if tone:
                dominant = max(tone, key=tone.get) if tone else None
                if dominant:
                    lines.append(f"  Dominant tone: {dominant}")
                    has_content = True
            phrases = style_profile.get("common_phrases", [])
            if phrases:
                lines.append(f"  Phrases they use: {', '.join(phrases[:8])}")
                has_content = True
            emoji_freq = style_profile.get("emoji_frequency")
            if emoji_freq is not None:
                if emoji_freq > 0.5:
                    lines.append("  Uses emojis frequently")
                elif emoji_freq < 0.1:
                    lines.append("  Rarely uses emojis")
                has_content = True

        # Add writing samples from actual posts
        if posts:
            samples = [p.get("text", "") for p in posts[:5] if p.get("text")]
            if samples:
                lines.append("  Recent post examples (match this voice):")
                for s in samples:
                    truncated = s[:200] + ("..." if len(s) > 200 else "")
                    lines.append(f'    "{truncated}"')
                has_content = True

        return "\n".join(lines) if has_content else ""

    def _build_facts_section(self, identity_mem: Dict[str, Any]) -> str:
        facts = identity_mem.get("facts", []) if identity_mem else []
        prefs = identity_mem.get("preferences", []) if identity_mem else []
        if not facts and not prefs:
            return ""
        lines = ["**Things known about them (from conversations):**"]
        for f in facts[:15]:
            fact_text = f.get("fact", "") if isinstance(f, dict) else str(f)
            if fact_text:
                lines.append(f"  - {fact_text}")
        for p in prefs[:10]:
            pref_text = p.get("preference", "") if isinstance(p, dict) else str(p)
            if pref_text:
                lines.append(f"  - Preference: {pref_text}")
        return "\n".join(lines) if len(lines) > 1 else ""

    def _build_emotional_section(self, summary: Dict[str, Any]) -> str:
        if not summary:
            return ""
        trend = summary.get("emotional_trend", "stable")
        avg = summary.get("avg_emotional_valence", 0)
        highlights = summary.get("recent_highlights", [])
        if not highlights and avg == 0:
            return ""
        lines = ["**Recent emotional patterns:**"]
        lines.append(f"  Trend: {trend}")
        if avg > 0.3:
            lines.append("  Generally in a positive state recently")
        elif avg < -0.3:
            lines.append("  Has been going through a tougher time recently")
        if highlights:
            lines.append("  Recent positive moments: " + ", ".join(
                h.get("type", "") for h in highlights[:3]
            ))
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # HELPERS – relationship classification
    # ------------------------------------------------------------------

    _FAMILY_KEYWORDS = {"wife", "husband", "daughter", "son", "mother", "father",
                        "sister", "brother", "parent", "child", "spouse", "partner",
                        "mom", "dad", "grandma", "grandpa", "uncle", "aunt", "cousin", "niece", "nephew"}
    _FRIEND_KEYWORDS = {"friend", "best friend", "close friend", "college friend", "buddy", "pal", "mate"}
    _COLLEAGUE_KEYWORDS = {"colleague", "coworker", "boss", "manager", "teammate", "mentor", "mentee",
                           "business partner", "co-founder"}

    @classmethod
    def _is_family(cls, c: Dict[str, Any]) -> bool:
        rel = (c.get("relationship") or "").lower()
        return any(k in rel for k in cls._FAMILY_KEYWORDS)

    @classmethod
    def _is_friend(cls, c: Dict[str, Any]) -> bool:
        rel = (c.get("relationship") or "").lower()
        return any(k in rel for k in cls._FRIEND_KEYWORDS)

    @classmethod
    def _is_colleague(cls, c: Dict[str, Any]) -> bool:
        rel = (c.get("relationship") or "").lower()
        return any(k in rel for k in cls._COLLEAGUE_KEYWORDS)

    # ------------------------------------------------------------------
    # DATA FETCHING (all fast MongoDB queries)
    # ------------------------------------------------------------------

    async def _get_graph_context(self, user_id: str) -> Dict[str, Any]:
        """Fetch graph context via GraphRAG (uses cached in-memory graph with edges)."""
        try:
            from domain.graph.rag import GraphRAG
            rag = GraphRAG(self.db)
            ctx = await rag.get_user_context(user_id, max_nodes=50)

            organized: Dict[str, list] = {
                "interests": [], "traits": [], "values": [],
                "preferences": [], "experiences": [], "connections": [],
            }
            type_mapping = {
                "interests": "interests", "traits": "traits", "values": "values",
                "preferences": "preferences", "experiences": "experiences",
                "connections": "connections", "demographics": "connections",
            }
            for key, items in ctx.items():
                target = type_mapping.get(key)
                if target and target in organized:
                    for item in items:
                        organized[target].append({
                            "label": item.get("label", ""),
                            "strength": item.get("strength", 0.5),
                            "properties": item.get("properties", {}),
                            "mention_count": item.get("properties", {}).get("evidence_count", 1),
                            "display_label": item.get("display_label", ""),
                            "connected": item.get("connected", []),
                        })

            identity_narrative = await rag.get_identity_context(
                user_id, action_type="personality_profile", max_tokens=2000,
            )
            organized["_identity_narrative"] = identity_narrative

            return organized
        except Exception as e:
            logger.error(f"Error fetching graph context: {e}")
            return {}

    async def _get_user_document(self, user_id: str) -> Dict[str, Any]:
        try:
            return await self.db.users.find_one(
                {"id": user_id},
                {
                    "_id": 0, "name": 1, "bio": 1, "interests": 1,
                    "avatar_name": 1, "avatar_bio": 1, "avatar_interests": 1,
                    "job_title": 1, "avatar_job_title": 1,
                    "location": 1, "avatar_location": 1, "age": 1,
                }
            ) or {}
        except Exception as e:
            logger.error(f"Error fetching user doc: {e}")
            return {}

    async def _get_identity_memory(self, user_id: str) -> Dict[str, Any]:
        try:
            doc = await self.db.identity_memory.find_one(
                {"user_id": user_id}, {"_id": 0}
            )
            return doc or {}
        except Exception as e:
            logger.error(f"Error fetching identity memory: {e}")
            return {}

    async def _get_recent_posts(self, user_id: str, limit: int = 30) -> List[Dict[str, Any]]:
        try:
            cursor = self.db.posts.find(
                {"user_id": user_id, "post_type": {"$in": ["real", None]}},
                {"_id": 0, "text": 1, "created_at": 1, "likes": 1, "comment_count": 1}
            ).sort("created_at", -1).limit(limit)
            return await cursor.to_list(limit)
        except Exception as e:
            logger.error(f"Error fetching posts: {e}")
            return []

    async def _get_all_connections(self, user_id: str) -> List[Dict[str, Any]]:
        try:
            user = await self.db.users.find_one({"id": user_id}, {"connections": 1})
            return user.get("connections", []) if user else []
        except Exception as e:
            logger.error(f"Error fetching connections: {e}")
            return []

    async def _get_style_profile(self, user_id: str) -> Optional[Dict[str, Any]]:
        try:
            doc = await self.db.avatar_style_profiles.find_one(
                {"user_id": user_id}, {"_id": 0}
            )
            return doc
        except Exception as e:
            logger.debug(f"No style profile for {user_id}: {e}")
            return None

    async def _get_episodic_summary(self, user_id: str) -> Dict[str, Any]:
        try:
            from domain.avatar.memory.episodic_memory import EpisodicMemory
            em = EpisodicMemory(self.db)
            return await em.get_emotional_summary(user_id, days=14)
        except Exception as e:
            logger.error(f"Error fetching episodic summary: {e}")
            return {}

    # ------------------------------------------------------------------
    # CACHE
    # ------------------------------------------------------------------

    async def _store_cache(self, user_id, prompt, graph_ctx, connections, style_profile):
        doc = {
            "user_id": user_id,
            "personality_prompt": prompt,
            "generated_at": datetime.now(timezone.utc),
            "generation_sources": {
                "graph_nodes_count": sum(len(v) for v in graph_ctx.values()) if isinstance(graph_ctx, dict) else 0,
                "connections_count": len(connections) if connections else 0,
                "has_style_profile": style_profile is not None,
            }
        }
        await self.db.avatar_personality_prompts.update_one(
            {"user_id": user_id}, {"$set": doc}, upsert=True
        )
